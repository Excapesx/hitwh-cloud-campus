export function inside(x,z) {
  let hit=false;
  for(let i=0,j=outline.length-1;i<outline.length;j=i++) {
    const a=outline[i],b=outline[j];
    if(((a.z>z)!==(b.z>z)) && x<(b.x-a.x)*(z-a.z)/(b.z-a.z)+a.x) hit=!hit;
  }
  return hit;
}
